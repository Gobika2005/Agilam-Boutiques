#!/usr/bin/env node
/**
 * bundle-migrations.mjs — concatenate the numbered SQL migrations into ONE
 * paste-ready file, so bringing a fresh TEST Supabase project up to date is a
 * single copy-paste into the SQL editor instead of 48 separate ones.
 *
 * Usage:
 *   npm run bundle-migrations                 # all migrations -> supabase/_bundle.sql
 *   npm run bundle-migrations -- --from 0044  # only 0044 and later (promote new work)
 *   npm run bundle-migrations -- --from 0044 --to 0048
 *   npm run bundle-migrations -- --out my.sql
 *
 * Then open the target project's SQL editor and run the generated file.
 * Migrations here are written to be idempotent, so re-running the bundle on an
 * existing DB is safe; --from lets you apply only what's new since prod.
 *
 * Zero dependencies — plain Node fs.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'supabase', 'migrations');

function arg(name, fallback = undefined) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const from = arg('from');
const to = arg('to');
const outName = arg('out', '_bundle.sql');
const outPath = join(root, 'supabase', outName);

// Sort lexically — the zero-padded 4-digit prefixes (0001..0048) sort correctly.
const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

const prefix = (f) => f.slice(0, 4);
const selected = files.filter((f) => {
  if (from && prefix(f) < String(from).padStart(4, '0')) return false;
  if (to && prefix(f) > String(to).padStart(4, '0')) return false;
  return true;
});

if (selected.length === 0) {
  console.error('No migrations matched the given range.');
  process.exit(1);
}

const parts = [
  '-- ============================================================',
  '-- GENERATED by scripts/bundle-migrations.mjs — do not edit by hand.',
  `-- Range: ${selected[0]} .. ${selected[selected.length - 1]}  (${selected.length} files)`,
  `-- Generated: ${new Date().toISOString()}`,
  '-- Paste-and-run in the target Supabase project SQL editor.',
  '-- ============================================================',
  '',
];

for (const f of selected) {
  const sql = readFileSync(join(migrationsDir, f), 'utf8').trimEnd();
  parts.push(`-- >>> ${f} >>>`, sql, `-- <<< ${f} <<<`, '');
}

writeFileSync(outPath, parts.join('\n'), 'utf8');
console.log(`Wrote ${selected.length} migrations (${selected[0]} .. ${selected[selected.length - 1]}) to`);
console.log(`  ${outPath}`);
console.log('Open the target Supabase project -> SQL editor -> paste this file -> Run.');
